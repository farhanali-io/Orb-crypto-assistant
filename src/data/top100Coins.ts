// Helper to generate a realistic 7d sparkline around a baseline
function generateSparkline(basePrice: number, change7d: number, points = 24): number[] {
  const result: number[] = [];
  const startPrice = basePrice / (1 + change7d / 100);
  let current = startPrice;
  const stepChange = (basePrice - startPrice) / points;
  for (let i = 0; i < points; i++) {
    const noise = (Math.random() - 0.49) * (basePrice * 0.025);
    current += stepChange + noise;
    result.push(Number(Math.max(current, basePrice * 0.5).toFixed(4)));
  }
  result[result.length - 1] = basePrice;
  return result;
}

